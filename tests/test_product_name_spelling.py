"""The name reads "SlowBooks Pro" everywhere (owner, 2026-11-19).

Every place a person reads the product's name spells it with a capital B:
the app's screens, its printed and PDF documents, its messages and emails,
the desktop launcher's windows and dialogs, and the guides. "Slowbooks"
(lower-case b) is left only where it is an identifier that an install, an
upgrade or another program depends on, each one named below; a new one has
to be added here on purpose. Older CHANGELOG entries keep the words they
were released with.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Identifiers, not text a person reads. Changing any of them breaks something.
ALLOWED = {
    "X-Slowbooks-Desktop",  # the desktop shell's request header (server + shim)
    "SlowbooksAuth",  # window globals the scripts share (auth.js)
    "SlowbooksDesktop",  # (desktop_shim.js)
    "SlowbooksTextSize",  # (text_size.js)
    "SlowbooksTopbar",  # (topbar_fit.js)
}

SURFACES = [
    "index.html",
    "desktop_launcher.py",
    "README.md",
    "INSTALL.md",
    "SECURITY.md",
    "CONTRIBUTING.md",
    "app/**/*.py",
    "app/templates/**/*.html",
    "app/static/js/*.js",
    "app/static/*.json",
    "docs/**/*.md",
    "cloudflare/*",
    "docker-entrypoint.sh",
]
VENDORED = {"app/static/js/chart.umd.js"}


def _files():
    seen = set()
    for pattern in SURFACES:
        for p in sorted(ROOT.glob(pattern)):
            rel = p.relative_to(ROOT).as_posix()
            if p.is_file() and rel not in VENDORED and rel not in seen:
                seen.add(rel)
                yield rel, p


def test_the_surfaces_exist():
    files = dict(_files())
    for must in (
        "index.html",
        "app/static/js/app.js",
        "app/templates/invoice_pdf.html",
        "docs/features.md",
        "desktop_launcher.py",
    ):
        assert must in files, must


def test_slowbooks_with_a_lower_case_b_is_only_an_identifier():
    found = []
    for rel, p in _files():
        text = p.read_text(encoding="utf-8", errors="replace")
        for n, line in enumerate(text.splitlines(), 1):
            for m in re.finditer(r"(?:X-)?Slowbooks[A-Za-z0-9_\-]*", line):
                if m.group(0) not in ALLOWED:
                    found.append(f"{rel}:{n}: {line.strip()[:120]}")
    assert not found, "write SlowBooks (capital B):\n" + "\n".join(found)


def test_the_unreleased_changelog_spells_it_right():
    # The newest section: "Unreleased" while it is open, else the release
    # section the release commit wrote in its place.
    log = (ROOT / "CHANGELOG.md").read_text(encoding="utf-8")
    newest = log.split("\n### ", 1)[1].split("\n### ", 1)[0]
    assert not re.search(r"Slowbooks(?![A-Za-z0-9_\-])", newest)


def test_the_window_and_the_documents_say_slowbooks_pro():
    shell = (ROOT / "index.html").read_text(encoding="utf-8")
    assert "<title>SlowBooks Pro 2026</title>" in shell
    app = (ROOT / "app/static/js/app.js").read_text(encoding="utf-8")
    assert "— SlowBooks Pro 2026`" in app
    inv = (ROOT / "app/templates/invoice_pdf.html").read_text(encoding="utf-8")
    assert "Generated by SlowBooks Pro 2026" in inv
