"""Giving statements: the ministry's own opening message and footer (#415).

The opening message is a saved giving-statement message (the invoice_messages
table, kind='giving_statement', #407) — its default one opens the statement.
The footer is a company setting (giving_statement_footer). Both are plain text
with line breaks, escaped on the page (no HTML injection). The IRS
acknowledgment sentence is always printed and is not editable. An empty
message or footer prints what printed before, minus the "Generated by
Slowbooks Pro 2026" line, which is gone either way. The same words ride on the
single PDF, the all-donors stack and the emailed copy — one code path.

WeasyPrint's native stack is not installed in CI, so render_pdf is stubbed to
return the rendered HTML — the template context and escaping are what these
assert, as the other giving-statement HTML tests do.
"""

import os
import uuid

import sqlalchemy as sa
from fastapi.testclient import TestClient

import pytest

from app.main import app
from app.models.audit import AuditLog
from app.models.settings import DEFAULT_SETTINGS
from app.schemas.invoice_messages import GIVING_STATEMENT_BODY_MAX

GENERATED_BY = "Generated by Slowbooks Pro 2026"
IRS_RETAIN = "Please retain this acknowledgment for your tax records."

MESSAGE = "Dear friend,\nThank you for your gifts to Harbor Light & Co <3."
FOOTER = (
    'Harbor Light Ministries\n123 Main St · EIN 12-3456789\n"Give & it shall be given."'
)


def _nonprofit(client):
    assert (
        client.put("/api/settings", json={"company_type": "nonprofit"}).status_code
        == 200
    )
    client.post("/api/nonprofit/setup-accounts")


def _receipt(client, customer_id, **over):
    body = {
        "customer_id": customer_id,
        "date": "2026-05-09",
        "tax_rate": "0",
        "method": "Credit Card",
        "lines": [
            {"description": "Spring gala ticket", "quantity": 1, "rate": "150.00"}
        ],
    }
    body.update(over)
    return client.post("/api/sales-receipts", json=body)


def _stub_render(monkeypatch):
    """render_pdf returns the HTML it was handed, so a PDF response body is
    the rendered template."""
    from app.services import pdf_service

    monkeypatch.setattr(pdf_service, "render_pdf", lambda html, **kw: html.encode())


def _giving_message(client, body=MESSAGE, name="Pastor's thanks", is_default=True):
    r = client.post(
        "/api/invoice-messages",
        json={
            "name": name,
            "body": body,
            "kind": "giving_statement",
            "is_default": is_default,
        },
    )
    assert r.status_code == 201, r.text
    return r.json()


def _set_footer(client, footer=FOOTER):
    assert (
        client.put(
            "/api/settings", json={"giving_statement_footer": footer}
        ).status_code
        == 200
    )


def _set_words(client, message=MESSAGE, footer=FOOTER):
    _giving_message(client, body=message)
    _set_footer(client, footer)


def _donor_with_gift(client, seed_customer):
    _nonprofit(client)
    client.put(f"/api/customers/{seed_customer.id}", json={"email": "d@example.org"})
    _receipt(client, seed_customer.id, date="2026-03-01")


