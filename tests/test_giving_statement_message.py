def test_single_stack_and_email_all_carry_the_words(
    client, monkeypatch, seed_accounts, seed_customer
):
    _stub_render(monkeypatch)
    _donor_with_gift(client, seed_customer)
    _set_words(client)

    one = client.get(
        f"/api/donors/{seed_customer.id}/giving-statement/pdf?year=2026"
    ).content.decode()
    stack = client.get("/api/donors/giving-statements/pdf?year=2026").content.decode()
    for html in (one, stack):
        assert "Dear friend," in html
        assert "Harbor Light Ministries" in html
        assert GENERATED_BY not in html

    import app.routes.donors as donors_routes

    captured = {}

    def _fake_send(db, to_email, attachment_bytes=None, **kw):
        captured["html"] = (attachment_bytes or b"").decode()
        return True

    donors_routes.send_email = _fake_send
    try:
        r = client.post(
            "/api/donors/giving-statements/batch-email", json={"year": 2026}
        )
    finally:
        from app.services.email_service import send_email as real_send

        donors_routes.send_email = real_send
    assert r.status_code == 200, r.text
    assert "Dear friend," in captured["html"]
    assert "Harbor Light Ministries" in captured["html"]
    assert GENERATED_BY not in captured["html"]


