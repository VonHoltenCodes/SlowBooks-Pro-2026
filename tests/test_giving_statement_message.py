def test_pdf_carries_default_message_and_footer_escaped_with_irs(
    client, monkeypatch, seed_accounts, seed_customer
):
    _stub_render(monkeypatch)
    _donor_with_gift(client, seed_customer)
    _set_words(client)
    html = client.get(
        f"/api/donors/{seed_customer.id}/giving-statement/pdf?year=2026"
    ).content.decode()
    # the ministry's words are present, line breaks kept
    assert "Dear friend,\nThank you for your gifts" in html
    assert "Harbor Light Ministries\n123 Main St" in html
    # escaped as text, never live HTML: the & and quotes are entities
    assert "Harbor Light &amp; Co &lt;3." in html
    assert "<3." not in html
    # the IRS sentence is always printed
    assert IRS_RETAIN in html
    # a donor's statement carries no product name
    assert GENERATED_BY not in html


