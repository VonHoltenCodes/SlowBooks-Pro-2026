def test_invoice_list_shows_only_invoice_kind(client):
    _nonprofit(client)
    client.post(
        "/api/invoice-messages", json={"name": "Pay by Zelle", "body": "Zelle here."}
    )
    _giving_message(client, body="Thank you.", name="Giving thanks")
    # the invoice form / list ask with no kind and see only invoice messages
    invoice = client.get("/api/invoice-messages").json()
    assert [m["name"] for m in invoice] == ["Pay by Zelle"]
    assert all(m["kind"] == "invoice" for m in invoice)
    # the giving list asks for its own kind
    giving = client.get("/api/invoice-messages?kind=giving_statement").json()
    assert [m["name"] for m in giving] == ["Giving thanks"]
    assert all(m["kind"] == "giving_statement" for m in giving)


def test_default_is_per_kind(client):
    _nonprofit(client)
    inv = client.post(
        "/api/invoice-messages",
        json={"name": "Inv default", "body": "Pay soon.", "is_default": True},
    ).json()
    giv = _giving_message(client, body="Thanks.", name="Giv default")
    # both remain the default of their own kind — neither cleared the other
    assert client.get("/api/invoice-messages").json()[0]["id"] == inv["id"]
    assert (
        client.get("/api/invoice-messages?kind=giving_statement").json()[0]["id"]
        == giv["id"]
    )
    assert inv["is_default"] is True and giv["is_default"] is True


