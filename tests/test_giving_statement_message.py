def _mint(client, label, role):
    r = client.post("/api/tokens", json={"label": label, "role": role})
    assert r.status_code == 201, r.text
    return r.json()["token"]


def _bearer(token):
    c = TestClient(app)
    c.headers["Authorization"] = f"Bearer {token}"
    return c


def test_only_an_admin_writes_the_words_but_anyone_may_preview(
    client, monkeypatch, seed_accounts, seed_customer
):
    _stub_render(monkeypatch)
    _donor_with_gift(client, seed_customer)

    keeper = _bearer(_mint(client, "keeper-bot", "bookkeeper"))
    reader = _bearer(_mint(client, "read-bot", "readonly"))
    admin = client  # signed in: no API token is an administrator (#434)

    footer = {"giving_statement_footer": "y"}
    msg = {"name": "n", "body": "x", "kind": "giving_statement"}

    assert keeper.put("/api/settings", json=footer).status_code == 403
    assert reader.put("/api/settings", json=footer).status_code == 403
    assert admin.put("/api/settings", json=footer).status_code == 200

    assert keeper.post("/api/invoice-messages", json=msg).status_code == 403
    assert reader.post("/api/invoice-messages", json=msg).status_code == 403
    assert admin.post("/api/invoice-messages", json=msg).status_code == 201

    # a preview is a read: every role may run it
    for api in (keeper, reader, admin):
        assert (
            api.get("/api/donors/giving-statement/preview?year=2026").status_code == 200
        )


