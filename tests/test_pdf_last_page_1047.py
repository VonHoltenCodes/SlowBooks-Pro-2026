def page_texts(pdf):
    pypdf = pytest.importorskip("pypdf")
    return [
        " ".join((p.extract_text() or "").split())
        for p in pypdf.PdfReader(io.BytesIO(pdf)).pages
    ]


def last_page_problems(pages, spec, n):
    """What is wrong with how a document of n rows ends, as sentences (none
    when it is right): the last page carries a row above its closing
    figures, every page after the first carries a row (so none holds only
    the footer or a closing block), the footer is drawn once, on the last
    page, and no summary splits across pages."""
    said = []
    row_pages = [
        k
        for k, p in enumerate(pages)
        if any(spec["row"](i) in p for i in range(1, n + 1))
    ]
    if len(pages) - 1 not in row_pages:
        said.append("the last page carries no row")
    for k in range(1, len(pages)):
        if k not in row_pages:
            said.append(f"page {k + 1} of {len(pages)} carries no row")
    for word in spec["closing"]:
        if word not in pages[-1]:
            said.append(f"{word!r} is not on the last page")
    if spec["footer"]:
        where = [k + 1 for k, p in enumerate(pages) if spec["footer"] in p]
        if where != [len(pages)]:
            said.append(f"the footer is on pages {where} of {len(pages)}")
    spread = {k for word in spec["together"] for k, p in enumerate(pages) if word in p}
    if len(spread) > 1:
        said.append(f"the summary splits across pages {sorted(k + 1 for k in spread)}")
    return said


@pytest.fixture
def made_pdfs(monkeypatch):
    """Every PDF the app renders, in order (the collection letter is not
    served by a route)."""
    from app.services import pdf_service

    seen = []
    real = pdf_service._write_pdf

    def keep(html):
        pdf = real(html)
        seen.append(pdf)
        return pdf

    monkeypatch.setattr(pdf_service, "_write_pdf", keep)
    return seen


def _check(client, accounts, kind, counts, made_pdfs):
    pytest.importorskip("pypdf")
    pytest.importorskip("weasyprint")
    spec = SPECS[kind]
    grown = {"pdfs": made_pdfs}
    wrong = []
    for n in counts:
        pdf = spec["make"](client, accounts, n, grown)
        assert pdf[:5] == b"%PDF-"
        for problem in last_page_problems(page_texts(pdf), spec, n):
            wrong.append(f"{kind}, {n} rows: {problem}")
    assert not wrong, "\n".join(wrong)


