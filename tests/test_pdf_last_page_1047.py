"""#1047 (2.32.0 round 21): the change order, the deposit, the customer
statement, the pay application, the collection letter and the giving
statement never end on a page with no row above their closing figures.

At particular lengths the last page of each held only its closing figures
and the footer (or the footer alone, or the IRS statement alone), or a
summary split across two pages. Each now closes its table the way the five
line documents do since #1039: the last row, the closing blocks and the
footer are one unbreakable row group (``tbody.doc-tail``). The Chromium half
of this is tests/test_print_last_sheet_1047_browser.py, which uses the makers
and the check below."""

import io

import pytest

MARK = "Generated by SlowBooks Pro 2026"

# the lengths the round-21 sweep found failing (on WeasyPrint's PDF or on
# Chromium's print), with the lengths either side of each run of them
CHANGE_ORDER = [1, 2, 26, 27, 28, 56, 57, 58, 59, 60, 61]
DEPOSIT = [1, 2, 25, 26, 27, 54, 55, 56, 57, 58, 59]
STATEMENT = [1, 2, 25, 26, 27, 53, 54, 55, 56, 57, 58, 59]
PAY_APPLICATION = [1, 2, 47, 48, 49, 50, 51]
COLLECTION_LETTER = [1, 2, 31, 32, 35, 38, 42, 43, 58, 59, 62, 66, 69, 70]
GIVING_STATEMENT = [1, 2, 19, 20, 22, 24, 26, 27, 50, 51, 52, 54, 56, 58, 59]


def row_amount(i):
    """The amount of row i, which names the row on the page (no total or
    running balance prints the same figure)."""
    return f"${1000 + i:,}.00"


def _customer(client, name):
    r = client.post("/api/customers?force=true", json={"name": name})
    assert r.status_code == 201, r.text
    return r.json()["id"]


def _pdf(client, url):
    r = client.get(url)
    assert r.status_code == 200, r.text[:300]
    return r.content


def _grow(client, grown, n, add):
    """One customer whose rows grow from length to length (the lengths
    rise), so a document of n rows costs n - (the last length) new rows:
    ``add(customer, i)`` adds row i."""
    if grown.get("customer") is None or grown.get("rows", 0) > n:
        grown["customer"] = _customer(client, f"Customer {len(grown)} {n}")
        grown["rows"] = 0
    while grown["rows"] < n:
        grown["rows"] += 1
        add(grown["customer"], grown["rows"])
    return grown["customer"]


# Each maker draws a document of n rows and answers its PDF; ``grown``
# carries what one length leaves for the next.


def change_order(client, accounts, n, grown):
    """A change order of n lines."""
    if "job" not in grown:
        customer = _customer(client, "Owner")
        job = client.post("/api/jobs", json={"customer_id": customer, "name": "Tower"})
        assert job.status_code == 201, job.text
        grown["job"] = job.json()["id"]
    lines = [
        {
            "description": f"Line {i:03d}",
            "cost_type": "material" if i % 2 else "labor",
            "quantity": 1,
            "unit_cost": 1000 + i,
        }
        for i in range(1, n + 1)
    ]
    r = client.post("/api/change-orders", json={"job_id": grown["job"], "lines": lines})
    assert r.status_code == 201, r.text
    return _pdf(client, f"/api/change-orders/{r.json()['id']}/pdf")


def deposit(client, accounts, n, grown):
    """A deposit of n checks, money that was never invoiced (#792), which
    prints a row each as a payment does."""
    others = [
        {
            "received_from": f"Payer {i}",
            "account_id": accounts["4000"].id,
            "check_number": str(i),
            "method": "Check",
            "amount": str(1000 + i),
        }
        for i in range(1, n + 1)
    ]
    r = client.post(
        "/api/deposits",
        json={
            "deposit_to_account_id": accounts["1000"].id,
            "date": "2026-09-12",
            "reference": f"SLIP-{n}",
            "line_ids": [],
            "other_lines": others,
            "total": str(sum(1000 + i for i in range(1, n + 1))),
        },
    )
    assert r.status_code == 200, r.text
    return _pdf(client, f"/api/deposits/{r.json()['transaction_id']}/pdf")


def _invoice(client, customer, i, sent=False, **dates):
    r = client.post(
        "/api/invoices",
        json={
            "customer_id": customer,
            "date": "2026-01-01",
            "tax_rate": 0,
            "lines": [{"description": "Sign", "quantity": 1, "rate": 1000 + i}],
            **dates,
        },
    )
    assert r.status_code == 201, r.text
    if sent:
        assert client.post(f"/api/invoices/{r.json()['id']}/send").status_code == 200


def statement(client, accounts, n, grown):
    """A customer statement of n invoices."""
    customer = _grow(client, grown, n, lambda c, i: _invoice(client, c, i))
    return _pdf(
        client,
        f"/api/reports/customer-statement/{customer}/pdf?as_of_date=2026-10-01",
    )


def pay_application(client, accounts, n, grown):
    """A pay application on a schedule of values of n lines."""
    customer = _customer(client, f"Builder {n}")
    job = client.post("/api/jobs", json={"customer_id": customer, "name": f"Job {n}"})
    assert job.status_code == 201, job.text
    job = job.json()["id"]
    r = client.put(
        f"/api/jobs/{job}/contract",
        json={
            "contract_type": "lump_sum",
            "contract_amount": 1000 * n,
            "retainage_pct": 10,
        },
    )
    assert r.status_code == 200, r.text
    sov = [
        {"description": f"Line {i:03d}", "kind": "work", "scheduled_value": 1000}
        for i in range(1, n + 1)
    ]
    assert client.put(f"/api/jobs/{job}/sov", json={"lines": sov}).status_code == 200
    r = client.post("/api/pay-applications", json={"job_id": job, "date": "2026-06-01"})
    assert r.status_code == 201, r.text
    return _pdf(client, f"/api/pay-applications/{r.json()['id']}/pdf")


def collection_letter(client, accounts, n, grown):
    """A collection letter for n overdue invoices. No route serves the
    letter, so the PDF is the last one the app made (``grown["pdfs"]``)."""
    customer = _grow(
        client,
        grown,
        n,
        lambda c, i: _invoice(client, c, i, sent=True, due_date="2026-01-31"),
    )
    r = client.post(
        "/api/reports/collection-letters",
        json={"letter_type": "30", "customer_ids": [customer], "send_email": False},
    )
    assert r.status_code == 200 and r.json()["generated"] == 1, r.text
    return grown["pdfs"][-1]


def _gift(client, donor, i):
    r = client.post(
        "/api/payments",
        json={"customer_id": donor, "date": "2026-03-01", "amount": str(1000 + i)},
    )
    assert r.status_code == 201, r.text


def giving_statement(client, accounts, n, grown):
    """A year-end giving statement of n gifts."""
    if not grown.get("nonprofit"):
        r = client.put("/api/settings", json={"company_type": "nonprofit"})
        assert r.status_code == 200, r.text
        client.post("/api/nonprofit/setup-accounts")
        grown["nonprofit"] = True
    donor = _grow(client, grown, n, lambda c, i: _gift(client, c, i))
    return _pdf(client, f"/api/donors/{donor}/giving-statement/pdf?year=2026")


