def test_a_report_keeps_its_total_with_the_row_above_it():
    """The report layout (report_pdf.html) keeps its last two rows in one
    unbreakable group: the A/R Aging's Total started the last page alone
    under the column headings at 49 customers (PDF) and 44 (Chromium)."""
    from app.services.pdf_service import render_report_html

    rows = [{"cells": [f"Customer {i}", "$1.00"]} for i in range(1, 6)]
    rows.append({"cells": ["Total", "$5.00"], "style": "grand-total"})
    section = {"title": "Aging", "period": "", "columns": ["Customer", "Total"]}
    html = render_report_html([{**section, "rows": rows}], {})
    assert "table.report > tbody.doc-tail { break-inside: avoid;" in html
    tail = html.split('<tbody class="doc-tail">')[1].split("</tbody>")[0]
    assert "Customer 5" in tail and "grand-total" in tail
    assert "Customer 4" not in tail
    # one row is a group of its own already
    one = render_report_html([{**section, "rows": rows[-1:]}], {})
    assert 'class="doc-tail"' not in one


def test_the_analytics_aging_keeps_its_total_with_the_last_row(
    client, seed_accounts, monkeypatch
):
    """The analytics PDF's aging table keeps its last row and TOTAL in one
    unbreakable group: TOTAL started a page alone at 41-42 customers."""
    from app.services import pdf_service

    drawn = []
    monkeypatch.setattr(
        pdf_service, "_write_pdf", lambda html: drawn.append(html) or b"%PDF-"
    )
    for i in (1, 2, 3):
        _invoice(client, _customer(client, f"Aging {i}"), i, sent=True)
    assert client.get("/api/analytics/export.pdf").status_code == 200
    html = drawn[-1]
    assert "table.data > tbody.doc-tail { break-inside: avoid;" in html
    tail = html.split('<tbody class="doc-tail">')[1].split("</tbody>")[0]
    assert "TOTAL" in tail and tail.count("<tr") == 2
