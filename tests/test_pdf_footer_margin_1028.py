"""#1028 (2.32.0 round 17, W-180): the saved PDF's footer sits in the page's
bottom margin box, so a full page's last line row never runs under it and
every page still carries it."""

import io

import pytest


def _lines_by_page(pdf_bytes):
    pypdf = pytest.importorskip("pypdf")
    reader = pypdf.PdfReader(io.BytesIO(pdf_bytes))
    pages = []
    for page in reader.pages:
        rows = []

        def visit(text, cm, tm, font_dict, font_size, rows=rows):
            t = (text or "").strip()
            if t:
                rows.append((round(tm[5]), t))

        page.extract_text(visitor_text=visit)
        pages.append(rows)
    return pages


def _long_invoice(client, seed_accounts, seed_customer, lines=45):
    r = client.post(
        "/api/invoices",
        json={
            "customer_id": seed_customer.id,
            "date": "2026-11-01",
            "tax_rate": 0,
            "lines": [
                {"description": f"Line {i}", "quantity": 1, "rate": 33}
                for i in range(1, lines + 1)
            ],
        },
    )
    assert r.status_code == 201, r.text
    return r.json()


def _assert_footer_alone_on_every_page(
    pdf_bytes, mark="Generated by Slowbooks Pro 2026"
):
    pages = _lines_by_page(pdf_bytes)
    assert len(pages) >= 2, "the fixture must fill more than one page"
    for n, rows in enumerate(pages, 1):
        ys = [y for y, t in rows if mark in t]
        assert ys, f"page {n} has no footer"
        fy = ys[0]
        others = [t for y, t in rows if abs(y - fy) < 6 and mark not in t]
        assert not others, f"page {n}: text beside the footer: {others}"
        # the footer is the lowest text on the page (pypdf's text space here
        # grows downward, as a standalone render showed)
        assert all(
            y < fy - 5 for y, t in rows if mark not in t
        ), f"page {n}: text below the footer"


def test_a_full_pages_last_row_never_runs_under_the_invoice_footer(
    client, seed_accounts, seed_customer
):
    inv = _long_invoice(client, seed_accounts, seed_customer)
    r = client.get(f"/api/invoices/{inv['id']}/pdf")
    assert r.status_code == 200 and r.content[:5] == b"%PDF-"
    _assert_footer_alone_on_every_page(r.content)


def test_the_two_line_footer_fits_too(client, seed_accounts, seed_customer):
    assert (
        client.put(
            "/api/settings", json={"invoice_footer": "Thank you - R17 footer"}
        ).status_code
        == 200
    )
    inv = _long_invoice(client, seed_accounts, seed_customer, lines=48)
    r = client.get(f"/api/invoices/{inv['id']}/pdf")
    assert r.status_code == 200
    pages = _lines_by_page(r.content)
    for n, rows in enumerate(pages, 1):
        assert any("Thank you - R17 footer" in t for _, t in rows), f"page {n}"
    _assert_footer_alone_on_every_page(r.content)


def test_the_browser_print_page_keeps_the_footer_in_the_flow(
    client, seed_accounts, seed_customer
):
    from app.routes._print import PRINT_STYLE

    inv = _long_invoice(client, seed_accounts, seed_customer, lines=3)
    page = client.get(f"/api/invoices/{inv['id']}/print-preview").text
    assert PRINT_STYLE in page and "running(doc-footer)" in page
    # the print script moves each document's footer to its end
    assert "fs[i].parentNode.appendChild(fs[i])" in page
