"""#1028 / #1030 (2.32.0 rounds 17 and 18): one rule for the footer on every
engine. It is drawn once, in the flow at the end of the document, kept with
the block before it, so no line row ever runs under it (W-180) and no sheet
carries it alone (NEW-255)."""

import io

import pytest

MARK = "Generated by SlowBooks Pro 2026"


def _rows_by_page(pdf_bytes):
    pypdf = pytest.importorskip("pypdf")
    reader = pypdf.PdfReader(io.BytesIO(pdf_bytes))
    pages = []
    for page in reader.pages:
        rows = []

        def visit(text, cm, tm, font_dict, font_size, rows=rows):
            t = (text or "").strip()
            if t:
                rows.append((round(tm[5]), t))

        page.extract_text(visitor_text=visit)
        pages.append(rows)
    return pages


def _long_invoice(client, seed_customer, lines=45):
    r = client.post(
        "/api/invoices",
        json={
            "customer_id": seed_customer.id,
            "date": "2026-11-01",
            "tax_rate": 0,
            "lines": [
                {"description": f"Line {i}", "quantity": 1, "rate": 33}
                for i in range(1, lines + 1)
            ],
        },
    )
    assert r.status_code == 201, r.text
    return r.json()


def _assert_footer_once_at_the_end(pdf_bytes):
    pages = _rows_by_page(pdf_bytes)
    assert len(pages) >= 2, "the fixture must fill more than one page"
    with_mark = [
        n for n, rows in enumerate(pages, 1) if any(MARK in t for _, t in rows)
    ]
    assert with_mark == [
        len(pages)
    ], f"the footer is on pages {with_mark} of {len(pages)}"
    rows = pages[-1]
    fy = next(y for y, t in rows if MARK in t)
    # nothing beside it, nothing below it (pypdf's text space here grows downward)
    assert not [t for y, t in rows if abs(y - fy) < 6 and MARK not in t]
    assert all(y < fy - 5 for y, t in rows if MARK not in t), "text below the footer"


def test_the_footer_is_once_at_the_end_and_over_no_row(
    client, seed_accounts, seed_customer
):
    inv = _long_invoice(client, seed_customer)
    r = client.get(f"/api/invoices/{inv['id']}/pdf")
    assert r.status_code == 200 and r.content[:5] == b"%PDF-"
    _assert_footer_once_at_the_end(r.content)


def test_the_two_line_footer_is_once_at_the_end_too(
    client, seed_accounts, seed_customer
):
    assert (
        client.put(
            "/api/settings", json={"invoice_footer": "Thank you - R19 footer"}
        ).status_code
        == 200
    )
    inv = _long_invoice(client, seed_customer, lines=48)
    r = client.get(f"/api/invoices/{inv['id']}/pdf")
    assert r.status_code == 200
    pages = _rows_by_page(r.content)
    assert [
        n
        for n, rows in enumerate(pages, 1)
        if any("Thank you - R19 footer" in t for _, t in rows)
    ] == [len(pages)]
    _assert_footer_once_at_the_end(r.content)


def test_the_print_page_is_the_pdfs_html_with_the_footer_last(
    client, seed_accounts, seed_customer
):
    inv = _long_invoice(client, seed_customer, lines=3)
    page = client.get(f"/api/invoices/{inv['id']}/print-preview").text
    body = page.split("<body")[1].split("</body>")[0]
    assert body.count('class="footer"') == 1
    assert body.index('class="footer"') > body.index("Line 3")
    assert "running(doc-footer)" not in page and "position: fixed" not in page


def _long_invoice_with_notes(client, seed_customer, lines, tax_rate=0):
    r = client.post(
        "/api/invoices",
        json={
            "customer_id": seed_customer.id,
            "date": "2026-11-01",
            "tax_rate": tax_rate,
            "notes": "Net 30. Thank you for your business.",
            "lines": [
                {
                    "description": f"Line {i}",
                    "quantity": 1,
                    "rate": 33,
                    "is_taxable": True,
                }
                for i in range(1, lines + 1)
            ],
        },
    )
    assert r.status_code == 201, r.text
    return r.json()


@pytest.mark.parametrize(
    "lines,tax_rate", [(55, 0), (54, 0.0825), (55, 0.0825), (56, 0), (53, 0)]
)
def test_the_totals_box_never_breaks_across_pages(
    client, seed_accounts, seed_customer, lines, tax_rate
):
    # #1033 (round 19, W-182): Subtotal on one page and Total on the next
    inv = _long_invoice_with_notes(client, seed_customer, lines, tax_rate)
    r = client.get(f"/api/invoices/{inv['id']}/pdf")
    assert r.status_code == 200
    pages = _rows_by_page(r.content)
    where = {}
    for n, rows in enumerate(pages, 1):
        for _, t in rows:
            for word in ("Subtotal", "Total", "Tax"):
                if t.startswith(word) or t == word:
                    where.setdefault(word, n)
    assert where["Subtotal"] == where["Total"], (lines, tax_rate, where)
    if tax_rate:
        assert where["Tax"] == where["Total"], (lines, tax_rate, where)
    # and the footer is still once, on the last page, with the notes
    _assert_footer_once_at_the_end(r.content)


def test_the_totals_box_is_a_block_not_a_float(client, seed_accounts, seed_customer):
    # #1032 (round 19, W-181): Chromium's break-before: avoid on the footer
    # binds to an in-flow block before it, never to a float
    inv = _long_invoice(client, seed_customer, lines=3)
    page = client.get(f"/api/invoices/{inv['id']}/print-preview").text
    assert (
        ".totals { margin-left: auto;" in page and ".totals { float: right" not in page
    )
    assert "break-inside: avoid" in page.split(".totals {")[1].split("}")[0]
